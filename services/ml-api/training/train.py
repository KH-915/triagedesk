"""
train.py — Train and evaluate the TF-IDF + Logistic Regression baseline.

Reads data/tickets.csv (columns: title, body, category), makes a fixed stratified
train/test split, fits the pipeline on the train split only, evaluates on the
held-out test split, then writes:
  - models/model.pkl            (the fitted sklearn Pipeline, loaded by app/predictor.py)
  - reports/model-evaluation.md (metrics actually measured by this run)

Usage: python training/train.py [--data data/tickets.csv] [--version v1.0.0]
"""

import argparse
import csv
import pickle
from datetime import date
from pathlib import Path

from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import classification_report, confusion_matrix, f1_score
from sklearn.model_selection import train_test_split
from sklearn.pipeline import Pipeline

SEED = 42
MAX_CHARS = 5000  # matches the truncation applied by the Node API and FastAPI schema


def load(path: Path) -> tuple[list[str], list[str], list[str]]:
    texts, labels, titles = [], [], []
    with open(path, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            # Same input shape as the Node API: "<title> <body>"
            texts.append(f"{row['title']} {row['body']}"[:MAX_CHARS])
            labels.append(row["category"])
            titles.append(row["title"])
    return texts, labels, titles


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="data/tickets.csv")
    ap.add_argument("--model-out", default="models/model.pkl")
    ap.add_argument("--report-out", default="../../reports/model-evaluation.md")
    ap.add_argument("--version", default="v1.0.0")
    args = ap.parse_args()

    X, y, _ = load(Path(args.data))
    # Drop exact-duplicate texts so an identical ticket cannot sit in both train and test.
    unique = dict.fromkeys(zip(X, y))
    X, y = [t for t, _ in unique], [l for _, l in unique]
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.2, stratify=y, random_state=SEED
    )

    pipeline = Pipeline(
        [
            ("tfidf", TfidfVectorizer(lowercase=True, ngram_range=(1, 2), min_df=2, sublinear_tf=True)),
            ("clf", LogisticRegression(max_iter=1000, random_state=SEED)),
        ]
    )
    pipeline.fit(X_train, y_train)

    pred = pipeline.predict(X_test)
    macro_f1 = f1_score(y_test, pred, average="macro")
    labels = sorted(set(y))
    report = classification_report(y_test, pred, labels=labels, digits=3)
    cm = confusion_matrix(y_test, pred, labels=labels)

    model_out = Path(args.model_out)
    model_out.parent.mkdir(parents=True, exist_ok=True)
    with open(model_out, "wb") as f:
        pickle.dump(pipeline, f)

    cm_rows = "\n".join(f"| {lab} | " + " | ".join(str(v) for v in row) + " |" for lab, row in zip(labels, cm))
    md = f"""# Model evaluation

Generated by `services/ml-api/training/train.py` on {date.today().isoformat()}. Model version: `{args.version}`.

## Setup
- Data: `{args.data}` — {len(X)} unique rows, {len(labels)} classes.
- Split: stratified 80/20 after removing exact-duplicate texts, `random_state={SEED}` ({len(X_train)} train / {len(X_test)} test).
- Model: `TfidfVectorizer(ngram_range=(1,2), min_df=2, sublinear_tf=True)` + `LogisticRegression`.

## Result on held-out test split
- **Macro-F1: {macro_f1:.3f}**

```
{report}
```

### Confusion matrix (rows = true, columns = predicted)
| true \\ pred | {" | ".join(labels)} |
|{"---|" * (len(labels) + 1)}
{cm_rows}

## Limitations — read before quoting any number
- The bundled dataset is **synthetic** (template-generated by `training/generate_data.py`).
  Only 5 hand-written core sentences exist per class, so test tickets are re-combinations of
  sentences the model saw in training. Scores are **heavily optimistic** and say nothing
  about performance on real customer text.
- No hyper-parameter search, no cross-validation, no calibration of `predict_proba`.
- Do not put these figures on a CV as real-world accuracy. Re-run on a real, licensed
  dataset (see docs in the project plan) and report that result instead.
"""
    report_out = Path(args.report_out)
    report_out.parent.mkdir(parents=True, exist_ok=True)
    report_out.write_text(md, encoding="utf-8")
    print(f"macro-F1={macro_f1:.3f}  model -> {model_out}  report -> {report_out}")


if __name__ == "__main__":
    main()
